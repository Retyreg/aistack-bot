"""Русские даты одним местом.

Дата потока меняется каждый набор, и до сентября 2026 она была вбита руками
в восемь user-facing строк — «25 июня», «10 июня», «13 августа». Пережить это
второй раз незачем: всё, что видит пользователь, рендерится отсюда из
COURSE_START / EARLYBIRD_DEADLINE / WEBINAR_AT.
"""

from datetime import date

MONTHS_RU = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)
WEEKDAYS_RU = ("пн", "вт", "ср", "чт", "пт", "сб", "вс")


def human_date(value: date) -> str:
    """«10 сентября» — родительный падеж, как в живой речи."""
    return f"{value.day} {MONTHS_RU[value.month - 1]}"
