def build_user_prompt(idea: str | None, answers: dict) -> str:
    """Собрать user-часть промпта. Пропуски помечаем явно — модели важно
    знать, что ответа не было, иначе она додумает его сама."""
    filled = {key: (answers.get(key) or "(не ответил)").strip() for key in QUESTION_KEYS}
    return VERDICT_USER_TEMPLATE.format(idea=(idea or "(не описана)").strip(), **filled)
